#!/usr/bin/env php
<?php

/**
 * Witness miner — turns a batch of traces into a plain-English invariant doc.
 *
 * Usage:
 *   ANTHROPIC_API_KEY=... php witness/bin/mine.php \
 *       --boundary=registration.pricing \
 *       --traces='var/witness/witness-*.jsonl' \
 *       --out=docs/invariants \
 *       [--max-traces=400] [--model=claude-opus-5] [--dry-run]
 *
 * Reads JSONL traces (already redacted by Witness), computes deterministic
 * per-field summary stats in PHP, samples raw traces, and asks Claude the
 * Daikon question: what was always true, and what was true ~99% of the time —
 * with the exceptions and their distinguishing fields. Output is one markdown
 * file per boundary, committed to the repo as living business-logic docs.
 *
 * Dependency-free by design (raw HTTPS via curl) so it runs from cron on the
 * legacy stack. If the team adopts Composer, the official SDK is
 * `composer require anthropic-ai/sdk`.
 */

const API_URL = 'https://api.anthropic.com/v1/messages';
const API_VERSION = '2023-06-01';
const DEFAULT_MODEL = 'claude-opus-5';
const MAX_OUTPUT_TOKENS = 16000;

main($argv);

function main(array $argv): void
{
    $opts = parseArgs($argv);
    $boundary = $opts['boundary'] ?? fail('--boundary is required');
    $glob = $opts['traces'] ?? fail('--traces is required (path or glob to JSONL files)');
    $outDir = $opts['out'] ?? 'docs/invariants';
    $maxTraces = (int) ($opts['max-traces'] ?? 400);
    $model = $opts['model'] ?? DEFAULT_MODEL;
    $dryRun = isset($opts['dry-run']);

    [$traces, $totalSeen, $firstTs, $lastTs] = loadTraces($glob, $boundary, $maxTraces);
    if ($totalSeen === 0) {
        fail("no traces found for boundary '$boundary' in $glob");
    }

    $stats = summarize($traces);
    $prompt = buildPrompt($boundary, $traces, $totalSeen, $firstTs, $lastTs, $stats);

    if ($dryRun) {
        fwrite(STDOUT, $prompt . "\n");
        fwrite(STDERR, sprintf(
            "[dry-run] boundary=%s traces_sampled=%d traces_total=%d window=%s..%s\n",
            $boundary, count($traces), $totalSeen, $firstTs, $lastTs
        ));
        return;
    }

    $apiKey = getenv('ANTHROPIC_API_KEY') ?: fail('ANTHROPIC_API_KEY is not set');
    $markdown = callClaude($apiKey, $model, $prompt);

    $header = sprintf(
        "<!-- Generated by witness/bin/mine.php. Do not hand-edit rules; annotate below each one. -->\n" .
        "# Invariants: %s\n\n" .
        "- **Observation window:** %s to %s (UTC)\n" .
        "- **Traces:** %d total, %d sampled for mining\n" .
        "- **Mined:** %s · model `%s`\n\n---\n\n",
        $boundary, $firstTs, $lastTs, $totalSeen, count($traces), gmdate('Y-m-d'), $model
    );

    if (!is_dir($outDir)) {
        mkdir($outDir, 0775, true);
    }
    $outPath = rtrim($outDir, '/') . '/' . str_replace('.', '-', $boundary) . '.md';
    file_put_contents($outPath, $header . trim($markdown) . "\n");
    fwrite(STDERR, "wrote $outPath\n");
}

/** @return array{0: array[], 1: int, 2: string, 3: string} sampled traces, total count, first/last ts */
function loadTraces(string $glob, string $boundary, int $maxTraces): array
{
    $files = glob($glob) ?: [];
    sort($files);

    $sample = [];
    $total = 0;
    $firstTs = null;
    $lastTs = null;

    foreach ($files as $file) {
        $fh = fopen($file, 'r');
        if ($fh === false) {
            continue;
        }
        while (($line = fgets($fh)) !== false) {
            $trace = json_decode(trim($line), true);
            if (!is_array($trace) || ($trace['boundary'] ?? null) !== $boundary) {
                continue;
            }
            $total++;
            $ts = $trace['ts'] ?? '';
            if ($firstTs === null || $ts < $firstTs) {
                $firstTs = $ts;
            }
            if ($lastTs === null || $ts > $lastTs) {
                $lastTs = $ts;
            }
            // Reservoir sampling: uniform sample without holding everything.
            if (count($sample) < $maxTraces) {
                $sample[] = $trace;
            } else {
                $j = mt_rand(0, $total - 1);
                if ($j < $maxTraces) {
                    $sample[$j] = $trace;
                }
            }
        }
        fclose($fh);
    }

    return [$sample, $total, $firstTs ?? '?', $lastTs ?? '?'];
}

/**
 * Deterministic per-field stats over the sampled traces so the model reasons
 * from counted facts, not just eyeballed examples. Flattens inputs/outputs
 * with dot paths; caps distinct-value lists.
 */
function summarize(array $traces): array
{
    $fields = [];
    foreach ($traces as $trace) {
        foreach (['inputs', 'outputs'] as $side) {
            flatten($trace[$side] ?? [], $side, $fields);
        }
    }

    $lines = [];
    $n = max(count($traces), 1);
    foreach ($fields as $path => $values) {
        arsort($values);
        $present = array_sum($values);
        $distinct = count($values);
        $top = array_slice($values, 0, 8, true);
        $topStr = implode(', ', array_map(
            fn($v, $c) => sprintf('%s ×%d', var_export($v, true), $c),
            array_keys($top), $top
        ));
        $suffix = $distinct > 8 ? sprintf(' … (%d distinct)', $distinct) : '';
        $lines[] = sprintf('%s — present in %d/%d: %s%s', $path, $present, $n, $topStr, $suffix);
    }
    sort($lines);
    return $lines;
}

function flatten(array $data, string $prefix, array &$fields): void
{
    foreach ($data as $key => $value) {
        $path = $prefix . '.' . $key;
        if (is_array($value)) {
            flatten($value, $path, $fields);
        } else {
            $repr = is_bool($value) ? ($value ? 'true' : 'false') : (string) ($value ?? 'null');
            if (strlen($repr) > 40) {
                $repr = substr($repr, 0, 40) . '…';
            }
            $fields[$path][$repr] = ($fields[$path][$repr] ?? 0) + 1;
        }
    }
}

function buildPrompt(string $boundary, array $traces, int $total, string $firstTs, string $lastTs, array $stats): string
{
    $traceLines = implode("\n", array_map(
        fn($t) => json_encode($t, JSON_UNESCAPED_SLASHES),
        $traces
    ));
    $statLines = implode("\n", $stats);
    $sampled = count($traces);

    return <<<PROMPT
You are mining business rules from production traces of a legacy event-management system (Sched). Each trace is one observed call at the boundary `$boundary`: redacted inputs and outputs as JSON. Identifier fields are salted hashes (same entity => same hash); `_dropped` counts redacted fields and is not a business value.

Observation window: $firstTs to $lastTs UTC. $total traces observed; $sampled sampled below. Per-field summary statistics over the sample:

<field_stats>
$statLines
</field_stats>

<traces>
$traceLines
</traces>

Answer the Daikon question, as a markdown document with exactly these sections:

## Always true
Invariants that held in every sampled trace. State each as a plain-English business rule an engineer could implement against ("If X then Y", "Z is always one of ..."), followed by the evidence in one short clause. Skip trivialities (schema facts, tautologies).

## True ~99% of the time — with exceptions
The priority section. Rules that held in almost every trace, with the exceptions enumerated: how many, and — critically — the distinguishing field values that separate the exceptions from the rule (e.g. "held in 4,312/4,326; the 14 exceptions all share plan='legacy-edu' and the same tenant hash"). These exceptions are where the edge-case business logic lives.

## Suspicious patterns
Anything that looks like a bug rather than a rule: contradictory outputs for identical inputs, error codes co-occurring with success flags, notifications sent on denial paths, etc.

## Coverage caveats
What this window cannot show (seasonal paths, rare code paths with zero traces, fields dropped by redaction) — so nobody over-trusts the rules above.

Rules must be grounded in the data provided; when the sample is too small to support a claim, say so instead of asserting it. Do not restate the trace schema.
PROMPT;
}

function callClaude(string $apiKey, string $model, string $prompt): string
{
    $body = json_encode([
        'model' => $model,
        'max_tokens' => MAX_OUTPUT_TOKENS,
        'messages' => [
            ['role' => 'user', 'content' => $prompt],
        ],
    ], JSON_UNESCAPED_SLASHES);

    $attempts = 0;
    $delay = 2;
    while (true) {
        $attempts++;
        $ch = curl_init(API_URL);
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_POST => true,
            CURLOPT_POSTFIELDS => $body,
            CURLOPT_TIMEOUT => 600,
            CURLOPT_HTTPHEADER => [
                'Content-Type: application/json',
                'x-api-key: ' . $apiKey,
                'anthropic-version: ' . API_VERSION,
            ],
        ]);
        $raw = curl_exec($ch);
        $status = curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
        $err = curl_error($ch);
        curl_close($ch);

        $retryable = $raw === false || $status === 429 || $status >= 500;
        if ($retryable && $attempts < 5) {
            fwrite(STDERR, "API attempt $attempts failed (status=$status $err), retrying in {$delay}s\n");
            sleep($delay);
            $delay *= 2;
            continue;
        }
        if ($raw === false) {
            fail("API request failed: $err");
        }

        $response = json_decode($raw, true);
        if ($status !== 200) {
            $msg = $response['error']['message'] ?? substr($raw, 0, 500);
            fail("API error (HTTP $status): $msg");
        }

        $stopReason = $response['stop_reason'] ?? null;
        if ($stopReason === 'refusal') {
            fail('the model declined this request (stop_reason=refusal); rerun or reduce the sample');
        }

        $text = '';
        foreach ($response['content'] ?? [] as $block) {
            if (($block['type'] ?? null) === 'text') {
                $text .= $block['text'];
            }
        }
        if ($text === '') {
            fail('empty response from API: ' . substr($raw, 0, 500));
        }
        if ($stopReason === 'max_tokens') {
            fwrite(STDERR, "warning: output truncated at max_tokens; consider --max-traces lower\n");
        }
        return $text;
    }
}

function parseArgs(array $argv): array
{
    $opts = [];
    foreach (array_slice($argv, 1) as $arg) {
        if (preg_match('/^--([^=]+)(?:=(.*))?$/', $arg, $m)) {
            $opts[$m[1]] = $m[2] ?? true;
        }
    }
    return $opts;
}

function fail(string $msg): never
{
    fwrite(STDERR, "mine.php: $msg\n");
    exit(1);
}
